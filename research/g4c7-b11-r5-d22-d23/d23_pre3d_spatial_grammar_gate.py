"""D23: Evidence-derived PRE-3D stop of a repeated-room grammar.
Runs on D22's independent SAVED-GLB measurements; never imports the generator.
Does not compute aesthetic scores or certify safe pedestrian access.
"""
import argparse, copy, json
from pathlib import Path

PENDING_ART='HUMAN_ART_REVIEW_REQUIRED'

def assess(evidence):
    assert evidence['stage']=='D22'
    assert evidence['scope']=='INDEPENDENT_SAVED_GLB_LOCAL_GEOMETRY_ONLY'
    assert evidence['saved_glbs_reloaded']==3
    assert evidence['adopted']==0 and evidence['construction']=='FORBIDDEN'
    assert evidence['formal_G0_S1_G1_G2_G3']=='NOT_RUN'
    assert evidence['overall']=='ART HOLD'
    counts=evidence['roof_template_repetition']['roof_panels_per_cell']
    # STOP condition is a provenance-backed design-repetition problem,
    # not a numerical beauty threshold.
    repetitive= len(counts)>=6 and len(set(counts.values()))==1 and evidence['roof_template_repetition']['all_8_cells_use_identical_ten_sector_annular_roof_grammar']
    route_dists=evidence['plan_route_to_room_distance_m']
    no_adjacent_access={k:v for k,v in route_dists.items() if v>12.0}
    # 12m is a provisional *study flag* for plans, not a code/standard.
    intersections=evidence['room_plan_intersections_over_1m2']
    flags={
        'single_roof_cell_grammar_repeated_everywhere':repetitive,
        'three_or_more_programs_not_on_tested_public_route':len(no_adjacent_access)>=3,
        'geometric_room_footprints_overlap_without_design_contract':len(intersections)>0,
        'no_verified_vertical_public_access':evidence['scope_limits']['vertical_access']=='NOT_MODELED',
        'formal_body_and_foot_sweeps_missing':evidence['scope_limits']['official_331_body_sweep']=='NOT_RUN' and evidence['scope_limits']['official_993_feet']=='NOT_RUN'
    }
    # Early design rejection cannot establish artistic merit; image review is separate.
    assert all(flags.values()),'D22 evidence changed; do not silently reuse old rejection logic'
    controls=evidence['counterfactual_dedicated_whole_cell_removed']
    assert all(controls.values()),'Cannot claim counterfactual clean if any dedicated geometry persists'
    return {'stage':'D23', 'evidence_stage':'D22', 'outcome':'PRE-3D STOP D22 GRAMMAR',
      'stop_reasons':flags,'non_adjacent_rooms_distance_m':no_adjacent_access,
      'room_footprint_overlaps':intersections,
      'counterfactual_cleanup':'DEDICATED ROOMS AND EQUIPMENT REMOVED IN GLB',
      'progress_vs_D20':'REMOVAL CLEANUP IMPROVED, BUT REPETITIVE PAVILIONS AND MISSING ROUTES',
      'art_judgement':'D22 PRE-G0 ART REJECT BY VISUAL REVIEW; NOT GENERATED BY GATE',
      'next_design_change':'Replace independent repeated cells with a single continuous inhabited urban fabric. Begin with an architect-authored human-scale promenade and 3D room adjacency/threshold plan; hold 3D mesh until an integrated macro silhouette is credible.',
      'required_before_next_3d':[
        'one shared drawing showing maker and research as real spatial activities, not colored labels',
        'the same authored original clearly produces a distinctive macro silhouette without eight identical roofs',
        'ground-level route physically intersects each target doorway/threshold',
        'a separate upper-level route design identifies actual stairs or lifts and all landing floors',
        'every room has a supported floor, non-colliding envelope, usable aperture and sky/light path',
        'activity removal deletes all associated floor, envelope, equipment and affected skyline',
        'human author explicitly rejects or approves pre-3D artistic promise; numerical gate alone cannot approve'
      ],'concept_only':True,'new_3d_promotion':False,
      'official_G0_S1_G1_G2_G3':'NOT_RUN','adopted':0,'overall':'ART HOLD',
      'Minecraft_Education':'FORBIDDEN','city_integration':'FORBIDDEN','PR53':'OPEN_DRAFT','main':'UNTOUCHED'}

def main():
    a=argparse.ArgumentParser();a.add_argument('--out',default='d22_build');args=a.parse_args()
    out=Path(args.out);evidence=json.loads((out/'d22_independent_result.json').read_text())
    summary=assess(evidence)
    # Metamorphic tests: if the D22 design was changed, fresh audit and fresh
    # author review are required rather than quietly calling the old verdict.
    mutant=copy.deepcopy(evidence)
    mutant['roof_template_repetition']['all_8_cells_use_identical_ten_sector_annular_roof_grammar']=False
    try:assess(mutant)
    except AssertionError:pass
    else:raise AssertionError('must catch outdated design grammar evidence')
    mutant=copy.deepcopy(evidence); mutant['overall']='ART PASS'
    try:assess(mutant)
    except AssertionError:pass
    else:raise AssertionError('must catch forged art status')
    mutant=copy.deepcopy(evidence)
    mutant['counterfactual_dedicated_whole_cell_removed']['no_maker_all_dedicated_cell_parts_absent']=False
    try:assess(mutant)
    except AssertionError:pass
    else:raise AssertionError('must catch falsely-clean removal scenario')
    (out/'d23_preflight_stop.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n')
    print('D23 early stop verified. D22 art REJECT by visual inspection; official QA/approval NOT RUN.')
if __name__=='__main__':main()
