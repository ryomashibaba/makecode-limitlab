def render(glb,out):
    import vtk
    scene=trimesh.load(glb,force='scene',process=False)
    for name,(eye,target,fov) in VISIONS.items():
        ren=vtk.vtkRenderer();ren.SetBackground(.88,.935,.955)
        win=vtk.vtkRenderWindow();win.SetOffScreenRendering(1);win.SetSize(1180,740);win.AddRenderer(ren)
        # ren.SetUseFXAA(False)  # disabled for headless stability
        for node in scene.graph.nodes_geometry:
            mat,gn=scene.graph[node];g=scene.geometry[gn].copy();g.apply_transform(mat)
            if not len(g.vertices):continue
            pts=vtk.vtkPoints()
            for v in g.vertices:pts.InsertNextPoint(*map(float,v))
            cells=vtk.vtkCellArray()
            for fc in g.faces:
                tri=vtk.vtkTriangle()
                for k,v in enumerate(fc):tri.GetPointIds().SetId(k,int(v))
                cells.InsertNextCell(tri)
            poly=vtk.vtkPolyData();poly.SetPoints(pts);poly.SetPolys(cells)
            mapper=vtk.vtkPolyDataMapper();mapper.SetInputData(poly)
            actor=vtk.vtkActor();actor.SetMapper(mapper)
            col=np.array(g.visual.vertex_colors).mean(axis=0)[:3]/255
            actor.GetProperty().SetColor(*map(float,col));actor.GetProperty().SetAmbient(.36)
            if '__fold_inner_' in node:actor.GetProperty().SetOpacity(.44)
            ren.AddActor(actor)
        l=vtk.vtkLight();l.SetPosition(20,-45,65);l.SetIntensity(1.55);ren.AddLight(l)
        cam=ren.GetActiveCamera();cam.SetPosition(*eye);cam.SetFocalPoint(*target)
        cam.SetViewAngle(fov);cam.SetViewUp(0,0,1)
        ren.ResetCameraClippingRange();win.Render()
        im=vtk.vtkWindowToImageFilter();im.SetInput(win);im.Update()
        w=vtk.vtkPNGWriter();w.SetFileName(str(out/(name+'.png')));w.SetInputConnection(im.GetOutputPort());w.Write()
        win.Finalize()

