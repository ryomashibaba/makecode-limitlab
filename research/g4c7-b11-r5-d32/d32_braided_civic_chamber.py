def put(s,name,mesh,role):
    if name in s.graph.nodes: raise ValueError('duplicate '+name)
    mesh.visual.vertex_colors=np.tile(np.array(COLORS[role],dtype=np.uint8),(len(mesh.vertices),1))
    s.add_geometry(mesh,geom_name=name,node_name=name)

def cube(s,name,xyz,size,role):
    m=trimesh.creation.box(extents=size);m.apply_translation(xyz);put(s,name,m,role)

def beam(s,name,p,q,r,role,sides=12):
    p,q=np.array(p,float),np.array(q,float);d=q-p
    m=trimesh.creation.cylinder(radius=r,height=np.linalg.norm(d),sections=sides)
    m.apply_transform(trimesh.geometry.align_vectors([0.,0.,1.],d));m.apply_translation((p+q)/2)
    put(s,name,m,role)

def polygon_prism(s,name,poly,z0,z1,role):
    # Polygon may be concave, use earcut through shapely triangulation with filtering.
    from shapely.geometry import Polygon
    from shapely.ops import triangulate
    shape=Polygon(poly)
    assert shape.is_valid and shape.area>0.01,name
    tri=[]
    for face in triangulate(shape):
        if shape.covers(face.representative_point()):
            c=list(face.exterior.coords)[:3];tri.append(c)
    vs=[];fs=[]
    for c in tri:
        idx=len(vs);vs.extend([(x,y,z0) for x,y in c]+[(x,y,z1) for x,y in c]);fs.extend([
         (idx,idx+2,idx+1),(idx+3,idx+4,idx+5),
         (idx,idx+1,idx+4),(idx,idx+4,idx+3),
         (idx+1,idx+2,idx+5),(idx+1,idx+5,idx+4),
         (idx+2,idx,idx+3),(idx+2,idx+3,idx+5)])
    put(s,name,trimesh.Trimesh(vertices=np.asarray(vs),faces=np.asarray(fs),process=False),role)

def quad_solid(s,name,top,bottom,role):
    # top/bottom: 4 ordered coresponding vertices, full watertight solid
    v=np.array(list(top)+list(bottom),float)
    f=[(0,1,2),(0,2,3),(4,7,6),(4,6,5),
        (0,4,5),(0,5,1),(1,5,6),(1,6,2),(2,6,7),(2,7,3),(3,7,4),(3,4,0)]
    put(s,name,trimesh.Trimesh(vertices=v,faces=f,process=False),role)

def profile(j):
    theta=ANGLE0+j*2*math.pi/S_COUNT
    # An asymmetric ellipse and a drifting inner luminous court. NOT 2 freestanding pavilions.
    x=(41+3.4*math.sin(3*theta))*math.cos(theta)+4.2*math.sin(theta)
    y=(31+3.7*math.cos(2*theta))*math.sin(theta)+3.2*math.cos(theta)
    xx=(14.4+1.3*math.sin(2*theta))*math.cos(theta)+2.4
    yy=(12.2+1.1*math.cos(3*theta))*math.sin(theta)+1.4
    outer_z=14.5+7.6*(0.5+0.5*math.sin(2*theta+.8))+2.8*math.cos(5*theta)
    inner_z=10.0+4.4*(.5+.5*math.cos(3*theta-.2))
    return (np.array((x,y)),np.array((xx,yy)),max(11.,outer_z),inner_z)

