#!/usr/bin/env python3
"""G4-C7 M37-P2 Blender DIRECT AUTHOR studio — empty real native master.

NO procedural building generation. Creates an EMPTY source .blend with author
collections and provisional cameras. Actual city form must be directly modelled
in Blender, not generated by this script, or recycled from rejected P1/O1/L/N.

Authoring UI is available by running the embedded script in Blender's Text Editor;
it supports checking readiness but does not certify safety, ART or provenance.
"""
from pathlib import Path
import sys

BASE = "M37P2_EMPTY_DIRECT_AUTHOR_MASTER_NOT_ART"
GROUPS = (
    "P2_CITY_MACRO_DIRECT_AUTHOR",
    "P2_INHABITED_SECTION_DIRECT_AUTHOR",
    "P2_PUBLIC_FACTORY_BOUNDARY_DIRECT_AUTHOR",
    "P2_RESEARCH_CULTURE_DIRECT_AUTHOR",
    "P2_HABITAT_PRIVATE_DIRECT_AUTHOR",
    "P2_CAMERA_RIG_NOT_ART",
)
CAMS = {
    "P2_CAMERA_AERIAL": ((190.0, -165.0, 132.0), (0.0, 0.0, 42.0), 32),
    "P2_CAMERA_PUBLIC_EYE": ((-84.0, -78.0, 12.0), (0.0, 0.0, 25.0), 29),
    "P2_CAMERA_HABITAT_EYE": ((-62.0, 50.0, 22.0), (0.0, 0.0, 28.0), 32),
}
UNITS = "ABSTRACT_ART_UNITS_NOT_METERS_NOT_BLOCKS"
CHARTER = {
    "P2_SOURCE_KIND": "UNAUTHORED_EMPTY_TEMPLATE",
    "P2_PARENT_REJECTED_FORM_IMPORTED": 0,
    "P2_ART": "HOLD",
    "P2_OFFICIAL_ADOPTIONS": 0,
    "P2_MINECRAFT": "FORBIDDEN",
    "P2_FORMAL_331_993": "NOT_RUN",
    "P2_MAKECODE_COST": "NOT_EVALUATED",
    "P2_AUTHOR_STUDIO_VERSION": 1,
    "P2_CAMERA_VIEWS_AUTHOR_APPROVED": False,
    "P2_STUDIO_STAGE": "EMPTY_NO_ART_CREATED",
}
REJECTED_PREFIXES = ("M37L_", "M37N_", "M37O_", "M37P1_", "M37M_EDIT_")


def _bpy():
    import bpy
    return bpy


def _mesh_members(collection):
    return {ob.name for ob in collection.all_objects
            if ob.type == "MESH" and len(ob.data.vertices) and len(ob.data.polygons)}


def scan(scene):
    """Editor readiness only. Nothing in this scan proves artistic quality."""
    errors = []
    for key in ("P2_PARENT_REJECTED_FORM_IMPORTED", "P2_OFFICIAL_ADOPTIONS"):
        if scene.get(key) != 0:
            errors.append("CHARTER_" + key)
    for key, expected in (
        ("P2_ART", "HOLD"), ("P2_MINECRAFT", "FORBIDDEN"),
        ("P2_FORMAL_331_993", "NOT_RUN"),
        ("P2_MAKECODE_COST", "NOT_EVALUATED"),
    ):
        if scene.get(key) != expected:
            errors.append("CHARTER_" + key)
    meshes = [ob for ob in scene.objects if ob.type == "MESH"]
    if any(ob.name.startswith(REJECTED_PREFIXES) for ob in meshes):
        errors.append("OLD_REJECTED_MESH_NAMES_NOT_PERMITTED")
    collections = {}
    for name in GROUPS:
        coll = _bpy().data.collections.get(name)
        if coll is None or coll not in scene.collection.children[:]:
            errors.append("MISSING_COLLECTION:" + name)
        else:
            collections[name] = _mesh_members(coll)
    if scene.get("P2_STUDIO_STAGE") != "EMPTY_NO_ART_CREATED":
        if not collections.get(GROUPS[0]):
            errors.append("MISSING_REAL_MACRO_CITY_MESH")
        if not collections.get(GROUPS[1]):
            errors.append("MISSING_REAL_INHABITED_SECTION_MESH")
        if not collections.get(GROUPS[2]):
            errors.append("MISSING_REAL_PUBLIC_STAFF_BOUNDARY_MESH")
        if not collections.get(GROUPS[3]):
            errors.append("MISSING_REAL_RESEARCH_CULTURE_MESH")
        if not collections.get(GROUPS[4]):
            errors.append("MISSING_REAL_HABITAT_PRIVATE_MESH")
    camera_names = {ob.name for ob in scene.objects if ob.type == "CAMERA"}
    if set(CAMS) - camera_names:
        errors.append("MISSING_THREE_REVIEW_CAMERAS")
    return {"errors": errors, "real_mesh_objects": len(meshes),
            "group_mesh_counts": {name: len(members) for name, members in collections.items()},
            "art": "HOLD", "formal_safety": "NOT_RUN",
            "MakeCode": "NOT_EVALUATED", "Minecraft": "FORBIDDEN"}


def make_empty_studio(filepath):
    bpy = _bpy()
    from mathutils import Vector
    filepath = Path(filepath).resolve()
    if filepath.exists():
        raise FileExistsError("APPEND_ONLY_SOURCE_MUST_BE_NEW")
    filepath.parent.mkdir(parents=True, exist_ok=True)
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.name = BASE
    for k, v in CHARTER.items():
        scene[k] = v
    scene["P2_STUDIO_UNITS"] = UNITS
    scene["P2_NO_AUTOMATIC_CITY_GEOMETRY"] = True
    scene["P2_ABSOLUTE_ART_GATE"] = "REQUIRED_3_REAL_NATIVE_IMAGES_NOT_YET_CREATED"
    scene.unit_settings.system = 'NONE'
    for name in GROUPS:
        coll = bpy.data.collections.new(name)
        scene.collection.children.link(coll)
    for name, (location, target, lens) in CAMS.items():
        data = bpy.data.cameras.new(name + "_DATA")
        data.lens = lens
        ob = bpy.data.objects.new(name, data)
        bpy.data.collections[GROUPS[-1]].objects.link(ob)
        ob.location = location
        ob.rotation_euler = (Vector(target) - ob.location).to_track_quat("-Z", "Y").to_euler()
        ob["P2_CAMERA_STATUS"] = "PROVISIONAL_REPOSITION_BY_AUTHOR_BEFORE_EARLY_ART"
    scene.camera = bpy.data.objects["P2_CAMERA_AERIAL"]
    scene.render.engine = "CYCLES"
    scene.render.resolution_x = 960
    scene.render.resolution_y = 600
    scene.render.resolution_percentage = 100
    scene.render.film_transparent = False
    if scene.world is None:
        scene.world = bpy.data.worlds.new('M37P2_DIRECT_AUTHOR_STUDIO_WORLD_NOT_ART')
    scene.world.color = (0.18, 0.18, 0.18)
    instruction = bpy.data.texts.new("M37P2_AUTHOR_HERE_FIRST_JA.txt")
    instruction.write(
        "M37-P2 NEW DIRECT AUTHOR MASTER: EMPTY, NOT ART.\\n"
        "Old P1, O1, L, N geometry must not be reused.\\n"
        "Model authentic whole-city rough fabric AND lived public/shipyard/"
        "research/habitat section together in THIS file using Blender GUI.\\n"
        "Move all three provisional cameras to genuine human viewpoints;\\n"
        "do not hide failed views. Save a NEW file name as a direct-authored source.\\n"
        "The review tool is inspection only. ART remains HOLD until human review.\\n"
        "No Minecraft world writes, no main changes, no automatic ART PASS.\\n"
        "Safety 331/993 and G0/S1/G1/G2/G3 have NOT RUN.\\n"
    )
    embedded = bpy.data.texts.new("M37P2_RUN_ONCE_ENABLE_AUTHOR_REVIEW_PANEL.py")
    embedded.write(Path(__file__).read_text(encoding="utf-8"))
    report = scan(scene)
    if report["errors"] or report["real_mesh_objects"] != 0:
        raise RuntimeError("EMPTY_STUDIO_NOT_CLEAN:" + str(report))
    bpy.ops.wm.save_as_mainfile(filepath=str(filepath), compress=False)
    return str(filepath)


def mark_scene_for_early_review(scene):
    """This is author declaration, NOT proof of direct editing / ART quality."""
    if scene.get("P2_STUDIO_STAGE") != "EMPTY_NO_ART_CREATED":
        raise ValueError("P2_STATE_ALREADY_CHANGED")
    result = scan(scene)
    if result["errors"]:
        raise ValueError("STUDIO_CHARTER_MISSING:" + ";".join(result["errors"]))
    required = GROUPS[:5]
    names = {group: _mesh_members(_bpy().data.collections[group]) for group in required}
    if any(not members for members in names.values()):
        raise ValueError("MACRO_AND_HUMAN_SECTION_MUST_HAVE_REAL_MESHES")
    if not scene.get("P2_CAMERA_VIEWS_AUTHOR_APPROVED", False):
        raise ValueError("AUTHOR_MUST_EXPLICITLY_REVIEW_AND_APPROVE_THREE_VIEW_POSITIONS")
    if len(set.union(*names.values())) < 5:
        raise ValueError("NOT_ENOUGH_DISTINCT_AUTHOR_MESH_EVIDENCE_OBJECTS")
    scene["P2_SOURCE_KIND"] = "DIRECT_EDITOR_AUTHORED_NATIVE_3D"
    scene["P2_STUDIO_STAGE"] = "DIRECT_AUTHOR_SUBMITTED_FOR_EARLY_ART_REVIEW_NOT_PASSED"
    return {"result": "ELIGIBLE_FOR_EARLY_IMAGE_RENDER_ONLY",
            "art": "HOLD", "official_adoptions": 0,
            "formal_331_993": "NOT_RUN", "Minecraft": "FORBIDDEN"}


def _sidebar():
    bpy = _bpy()
    class G4C7_OT_P2_audit(bpy.types.Operator):
        bl_idname = "g4c7.p2_direct_author_audit"
        bl_label = "Check native editor evidence (NOT ART)"
        def execute(self, context):
            result = scan(context.scene)
            if result["errors"]:
                self.report({'WARNING'}, str(result["errors"])[:200])
            else:
                self.report({'INFO'}, "Source gate OK, NOT ART OR SAFETY PASS")
            return {'FINISHED'}

    class G4C7_OT_P2_mark(bpy.types.Operator):
        bl_idname = "g4c7.p2_direct_author_mark"
        bl_label = "Submit manually modelled master for 3-view review"
        def execute(self, context):
            try:
                mark_scene_for_early_review(context.scene)
            except Exception as exc:
                self.report({'ERROR'}, str(exc)[:220])
                return {'CANCELLED'}
            self.report({'INFO'}, "REVIEW ONLY. Save as NEW .blend. ART still HOLD.")
            return {'FINISHED'}

    class G4C7_PT_P2_author(bpy.types.Panel):
        bl_label = "G4-C7 M37-P2 Direct Author"
        bl_idname = "G4C7_PT_P2_DIRECT_AUTHOR"
        bl_space_type = 'VIEW_3D'
        bl_region_type = 'UI'
        bl_category = "P2 Author"
        def draw(self, context):
            layout = self.layout
            layout.label(text="DIRECT GUI MODEL ONLY; ART HOLD", icon="ERROR")
            layout.label(text="Sculpt city fabric and lived section TOGETHER.")
            layout.label(text="No P1/O1/L/N form reuse; no auto city.")
            layout.label(text="Place authored meshes in five collections.")
            layout.prop(context.scene, "p2_camera_author_approved",
                        text="I checked all 3 true camera positions")
            layout.operator("g4c7.p2_direct_author_audit")
            layout.operator("g4c7.p2_direct_author_mark")
            layout.label(text="Saved original must be a NEW .blend.")
            layout.label(text="331/993 NOT RUN; Minecraft FORBIDDEN.")

    return G4C7_OT_P2_audit, G4C7_OT_P2_mark, G4C7_PT_P2_author


def register():
    bpy = _bpy()
    from bpy.props import BoolProperty
    classes = _sidebar()
    for cls in classes:
        if not hasattr(bpy.types, cls.__name__):
            bpy.utils.register_class(cls)
    bpy.types.Scene.p2_camera_author_approved = BoolProperty(
        name="Three cameras verified by artist", default=False,
        description="Declaration, not proof of ART validity",
        update=lambda self, ctx: self.__setitem__(
            "P2_CAMERA_VIEWS_AUTHOR_APPROVED", bool(self.p2_camera_author_approved))
    )


if __name__ == "__main__":
    if "--create-template" in sys.argv:
        position = sys.argv.index("--create-template")
        if position + 1 >= len(sys.argv):
            raise SystemExit("Missing output .blend path")
        print("P2_EMPTY_ARTIST_STUDIO_CREATED", make_empty_studio(sys.argv[position + 1]))
    else:
        # In embedded Blender Text Editor: Register only; do NOT generate geometry.
        register()
