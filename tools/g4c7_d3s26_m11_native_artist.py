#!/usr/bin/env python3
"""D3S26 M11: protected native edit and 8-camera review. NOT city or ART PASS."""
import hashlib,json,os,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'artifacts/g4c7-a72-authored-native/native-output/a72_authored_true_section.blend'
OUT=ROOT/'artifacts/g4c7-d3s26-m11-native-artist'/('run_'+os.environ.get('GITHUB_SHA','local')[:12])
CAMS={
'south':((0,-125,57),(5,16,12)),
'north':((0,125,64),(5,16,12)),
'oblique':((-95,-82,77),(6,18,12)),
'district':((74,-64,48),(2,20,11)),
'market_eye':((-19,-12,1.7),(-20,7,2.7)),
'maker_eye':((12,6,1.7),(24,16,4.1)),
'research_eye':((-2,31,9.0),(20,16,3.5)),
'resident_eye':((29,38,15.1),(0,12,9.0))}
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def preflight():
 assert len(CAMS)==8 and len(set(CAMS))==8
 assert BASE!=OUT and str(OUT).startswith(str(ROOT))
 return {'cameras':8,'base':str(BASE.relative_to(ROOT)),
         'ART':'HOLD','construction':'FORBIDDEN','integration':'FORBIDDEN',
         'formal_331_993':'NOT_RUN','G0_S1_G1_G2_G3':'NOT_RUN'}
def build():
 import bpy
 from mathutils import Vector
 status=preflight()
 assert BASE.is_file() and BASE.stat().st_size>100000
 assert not OUT.exists(),'append-only artifact exists'
 OUT.mkdir(parents=True)
 bpy.ops.wm.open_mainfile(filepath=str(BASE))
 for name in ('MARKET','MAKER','READING','HOUSING'):
  ob=bpy.data.objects.get(name+'_TRUE_INTERIOR_FLOOR')
  assert ob and ob.type=='MESH',name
 before=len(bpy.data.objects)
 scene=bpy.context.scene
 col=bpy.data.collections.new('M11_DIRECT_NATIVE_AUTHOR_EDITS')
 scene.collection.children.link(col)
 def mat(n,color,metal=0):
  m=bpy.data.materials.new(n);m.use_nodes=True
  p=m.node_tree.nodes.get('Principled BSDF')
  p.inputs['Base Color'].default_value=(*color,1)
  p.inputs['Metallic'].default_value=metal
  p.inputs['Roughness'].default_value=.41
  return m
 ceramic=mat('M11_CivicCeramic',(.29,.53,.63),.2)
 copper=mat('M11_PublicWarmMetal',(.67,.40,.23),.26)
 greens=mat('M11_PlantedCivicCourts',(.10,.35,.25))
 floor=mat('M11_CivicGallerySurface',(.42,.48,.41))
 def mesh(name,verts,faces,material):
  assert len(verts)>=3 and len(faces)>=1
  assert all(0<=j<len(verts) for f in faces for j in f)
  data=bpy.data.meshes.new(name+'_EDITABLE_MESH')
  data.from_pydata(verts,[],faces);data.update()
  ob=bpy.data.objects.new(name,data);col.objects.link(ob)
  data.materials.append(material)
  ob['STATUS']='ART_HOLD_ROUTE_UNCERTIFIED'
  return ob
 def quad(name,p,material,thick=.4):
  ob=mesh(name,p,[(0,1,2,3)],material)
  mod=ob.modifiers.new('PhysicalThickness','SOLIDIFY');mod.thickness=thick
  return ob
 # Authored station controls rather than autogenerated towers, storeys or bay arrays.
 ribs=[
  [(-33,-8,3),(-27,-1,12),(-19,8,19),(-12,16,23)],
  [(-25,-10,3),(-18,-2,16),(-8,10,22),(2,17,29)],
  [(-8,-9,4),(-3,1,18),(10,13,24),(22,17,27)],
  [(8,-9,5),(12,0,17),(26,8,20),(37,16,22)],
  [(23,-2,5),(29,5,15),(35,12,19),(43,26,19)]]
 for k,(a,b) in enumerate(zip(ribs,ribs[1:])):
  for i in (1,2):
   ob=quad('M11_CIVIC_DAYLIGHT_FACET_%d_%d'%(k,i),
           [a[i],b[i],b[i+1],a[i+1]],ceramic if (k+i)%2 else copper,1.15)
   bevel=ob.modifiers.new('SmoothEdges','BEVEL');bevel.width=.24;bevel.segments=2
 # Deliberately place a broad civic gallery between occupied destination volumes.
 bridge=[(-14,20,7.2),(-10,22,7.2),(2,27,8.3),(5,31,8.3),(12,33,9.8),(16,37,9.8)]
 left=[(x-3.4,y,z) for x,y,z in bridge]
 right=[(x+3.4,y,z) for x,y,z in bridge]
 for i in range(len(bridge)-1):
  quad('M11_OCCUPIED_GALLERY_%02d'%i,
       [left[i],left[i+1],right[i+1],right[i]],floor,.38)
 # Public garden and a second elevated inhabited garden, not a complete route.
 for tag,poly,z in (
  ('ARRIVAL',[(-25,-14),(-9,-17),(-1,-10),(-14,-3),(-29,-6)],.12),
  ('ELEVATED',[(14,32),(25,30),(33,38),(21,44),(11,39)],12.9)):
  ob=mesh('M11_'+tag+'_GARDEN_SURFACE',
          [(x,y,z) for x,y in poly],[tuple(range(len(poly)))],greens)
  ob.modifiers.new('GardenBedThickness','SOLIDIFY').thickness=.45
 # Native edits to old stored mesh vertices; never overwrite historical A72.
 for name,dz in (('READING',3.2),('HOUSING',2.4)):
  ob=bpy.data.objects.get(name+'_INDIVIDUAL_FOLDED_ROOF')
  assert ob and ob.type=='MESH' and len(ob.data.vertices)>=4
  ob.data.vertices[0].co.z+=dz
  ob.data.vertices[2].co.z+=dz*.62
  ob.data.update()
 scene['PROJECT']='G4-C7 D3S26 M11 NATIVE METHOD TRIAL'
 scene['ART_DECISION']='HOLD_REAL_IMAGE_REVIEW_REQUIRED'
 scene['FORMAL_331_993_GATES']='NOT_RUN'
 scene['MINECRAFT_EDUCATION_WRITES']=0
 scene['OLD_A72_REFERENCE']='TECHNICAL_SEED_NOT_ART_APPROVED'
 scene.render.engine='CYCLES'
 scene.cycles.samples=10
 scene.render.resolution_x=800;scene.render.resolution_y=450
 scene.render.resolution_percentage=100
 scene.render.image_settings.file_format='PNG'
 scene.view_settings.view_transform='AgX'
 for name,(pos,target) in CAMS.items():
  cam=bpy.data.cameras.new('M11_CAM_'+name)
  ob=bpy.data.objects.new('M11_CAM_'+name,cam)
  col.objects.link(ob);ob.location=pos
  ob.rotation_euler=(Vector(target)-ob.location).to_track_quat('-Z','Y').to_euler()
  cam.lens=33 if 'eye' in name else 39
 scene.camera=bpy.data.objects['M11_CAM_oblique']
 saved=OUT/'M11_NATIVE_EDITED_FROM_A72_TECH_SEED.blend'
 assert not saved.exists()
 bpy.ops.wm.save_as_mainfile(filepath=str(saved),check_existing=False)
 imgs={}
 for name in CAMS:
  scene.camera=bpy.data.objects['M11_CAM_'+name]
  png=OUT/('M11_'+name+'.png')
  scene.render.filepath=str(png)
  bpy.ops.render.render(write_still=True)
  assert png.exists() and png.stat().st_size>1024
  imgs[name]={'sha256':sha(png),'bytes':png.stat().st_size}
 glb=OUT/'M11_NATIVE_EDITED_GEOMETRY_UNASSESSED.glb'
 bpy.ops.object.select_all(action='DESELECT')
 for ob in bpy.data.objects:
  if ob.type=='MESH' and not ob.hide_render:ob.select_set(True)
 bpy.ops.export_scene.gltf(filepath=str(glb),export_format='GLB',use_selection=True)
 assert glb.exists() and glb.stat().st_size>2000
 result={'stage':'D3S26_M11_NATIVE_FIRST_CYCLE',
         'source_blend_sha256':sha(BASE),'saved_blend_sha256':sha(saved),
         'glb_sha256':sha(glb),'source_object_count':before,
         'new_object_count':len(bpy.data.objects)-before,
         'views':imgs,'status':status,'blender':bpy.app.version_string,
         'warning':'No ART, routes, G0-S1-G1-G2-G3 or Minecraft approval'}
 (OUT/'manifest.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
 print('M11_NATIVE_BLEND_AND_EIGHT_VIEWS_WRITTEN_ART_HOLD',OUT)
if __name__=='__main__':
 if '--preflight' in sys.argv: print(json.dumps(preflight(),indent=2))
 else:build()
