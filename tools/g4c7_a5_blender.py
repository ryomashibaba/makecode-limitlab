import bpy, math, json, argparse, sys, os
from mathutils import Vector
from pathlib import Path

def mat(name, color, metal=0, rough=.5):
    m=bpy.data.materials.new(name); m.diffuse_color=(*color,1); m.use_nodes=True
    p=next(n for n in m.node_tree.nodes if n.type=='BSDF_PRINCIPLED')
    p.inputs['Base Color'].default_value=(*color,1)
    p.inputs['Metallic'].default_value=metal; p.inputs['Roughness'].default_value=rough
    return m

def mesh(name, verts, faces, material):
    me=bpy.data.meshes.new(name); me.from_pydata(verts,[],faces); me.update()
    ob=bpy.data.objects.new(name,me); bpy.context.collection.objects.link(ob)
    ob.data.materials.append(material); return ob

def box(name, loc, size, material):
    bpy.ops.mesh.primitive_cube_add(size=1,location=loc); ob=bpy.context.object
    ob.name=name; ob.dimensions=size; bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    ob.data.materials.append(material); return ob

def beam(name,a,b,r,material):
    a,b=Vector(a),Vector(b); d=b-a
    bpy.ops.mesh.primitive_cylinder_add(vertices=8,radius=r,depth=d.length,location=(a+b)/2)
    ob=bpy.context.object; ob.name=name; ob.rotation_euler=d.to_track_quat('Z','Y').to_euler(); ob.data.materials.append(material)
    return ob

def strip(name, inner, outer, ya,yb, material):
    # Closed arch-sector prism; inner/outer lists lie in X/Z plane.
    vs=[]
    for y in [ya,yb]:
        for curve in [inner,outer]: vs += [(x,y,z) for x,z in curve]
    n=len(inner); fs=[]
    for i in range(n-1):
        fs += [(i,i+1,n+i+1,n+i),(2*n+i,3*n+i,3*n+i+1,2*n+i+1),
               (i,2*n+i,2*n+i+1,i+1),(n+i,n+i+1,3*n+i+1,3*n+i)]
    fs += [(0,n,3*n,2*n),(n-1,3*n-1,4*n-1,2*n-1)]
    return mesh(name,vs,fs,material)

def path_deck(name, pts, width, thickness, material):
    vs=[]; fs=[]
    for i,p in enumerate(pts):
        d=Vector(pts[min(i+1,len(pts)-1)])-Vector(pts[max(0,i-1)])
        normal=Vector((-d.y,d.x,0)).normalized()*width/2
        for dz in [-thickness,0]:
            for side in [-1,1]: vs.append(tuple(Vector(p)+normal*side+Vector((0,0,dz))))
    for i in range(len(pts)-1):
        k=i*4; q=k+4
        fs += [(k,q,q+1,k+1),(k+2,k+3,q+3,q+2),(k,k+2,q+2,q),(k+1,q+1,q+3,k+3)]
    fs += [(0,1,3,2),(len(vs)-4,len(vs)-2,len(vs)-1,len(vs)-3)]
    return mesh(name,vs,fs,material)

def camera(scene,name,pos,target,scale):
    ca=bpy.data.cameras.new(name); ob=bpy.data.objects.new(name,ca); scene.collection.objects.link(ob)
    ob.location=pos; ob.rotation_euler=(Vector(target)-ob.location).to_track_quat('-Z','Y').to_euler()
    ca.type='ORTHO'; ca.ortho_scale=scale; ca.lens=45; scene.camera=ob; return ob

def configure(scene):
    scene.render.engine='BLENDER_EEVEE'; scene.render.image_settings.color_mode='RGB'
    scene.render.resolution_x=2048; scene.render.resolution_y=1536; scene.render.resolution_percentage=100
    scene.render.image_settings.file_format='PNG'
    scene.world=bpy.data.worlds.new(scene.name+' sky'); scene.world.use_nodes=True
    bg=next(n for n in scene.world.node_tree.nodes if n.type=='BACKGROUND'); bg.inputs[0].default_value=(.49,.63,.78,1); bg.inputs[1].default_value=.55
    scene.view_settings.view_transform='AgX'
    ld=bpy.data.lights.new('Large soft sun','SUN'); lo=bpy.data.objects.new('Large soft sun',ld); scene.collection.objects.link(lo)
    ld.energy=3; ld.angle=.18; lo.rotation_euler=(.45,-.65,-.5)

def shots(scene,out,scale=220,target=(0,0,24)):
    positions={'front':(0,-300,57),'oblique':(225,-290,190),'side':(300,0,64),'aerial':(90,-110,390)}
    cams={}
    for name,pos in positions.items(): cams[name]=camera(scene,name,pos,target,scale)
    for name,cam in cams.items():
        scene.camera=cam; scene.render.filepath=str(out/(name+'.png')); bpy.ops.render.render(write_still=True)
    scene.camera=cams['oblique']
    return cams

def baseline(data, mats):
    sc=bpy.data.scenes.new('A4_BASELINE_CITY'); bpy.context.window.scene=sc; configure(sc)
    # Exact A4 geometry; only axis conversion X,Y(height),Z -> X,-Z,Y.
    for b in data['boxes']:
        region=b['id'][0]; material=mats.get(region,mats['concrete'])
        if b['material']=='glass': material=mats['glass']
        box(b['id']+'_'+b['role'],(b['x']+b['w']/2-186,186-b['z']-b['d']/2,b['y']+b['h']/2), (b['w'],b['d'],b['h']),material)
    box('Reference ground',(0,0,-1),(390,390,2),mats['ground'])
    return sc

def proposal(m):
    sc=bpy.data.scenes.new('A5_B_ORBITAL_COMMONS'); bpy.context.window.scene=sc; configure(sc)
    box('District base',(0,0,-2),(188,178,4),m['ground'])
    # Four visible road stubs; pedestrian apron crosses their inner ends.
    for x in [-86,86]: box('N-S road',(x,0,.04),(10,178,.08),m['road'])
    for y in [-79,79]: box('E-W road',(0,y,.05),(188,10,.1),m['road'])
    box('Public ground, continuous N-S axis',(0,0,.4),(24,158,.8),m['stone'])
    box('Public ground, continuous E-W axis',(0,0,.45),(170,16,.9),m['stone'])
    for y,center in [(-20,55),(20,50)]:
        for sign in [-1,1]:
            box('Main vault ground footing',(sign*center,y,1),(18,18,2),m['terrace'])
    for sign in [-1,1]:
        box('Transverse vault ground footing',(-30,sign*55,1),(20,20,2),m['terrace'])
    # Two deep hollow inhabited arches. Not a roof plate: 14-17m radial band,
    # with inner/outer structural shells, glazed side walls and open cavity.
    N=72
    for label,y,rx,rz in [('SOUTH',-20,62,64),('NORTH',20,57,53)]:
        ts=[math.pi*i/N for i in range(N+1)]
        inn=[((rx-14)*math.cos(t),2+(rz-15)*math.sin(t)) for t in ts]
        out=[(rx*math.cos(t),2+rz*math.sin(t)) for t in ts]
        inside=[((rx-12)*math.cos(t),2+(rz-13)*math.sin(t)) for t in ts]
        outside=[((rx-2)*math.cos(t),2+(rz-2)*math.sin(t)) for t in ts]
        strip(label+' inner load shell',inn,inside,y-7,y+7,m['stone'])
        strip(label+' outer load shell',outside,out,y-7,y+7,m['stone'])
        for side in [-1,1]:
            yy=y+side*6.8
            strip(label+' continuous glazed occupied band',inside,outside,yy-.18,yy+.18,m['glass'])
        # Actual transverse diaphragms; dark edges disclose depth, rather than fins.
        for j in range(0,N+1,6):
            a=inn[j]; b=out[j]
            beam(label+' diaphragm '+str(j),(a[0],y-7,a[1]),(b[0],y-7,b[1]),.35,m['dark'])
            beam(label+' diaphragm rear '+str(j),(a[0],y+7,a[1]),(b[0],y+7,b[1]),.35,m['dark'])
        # Horizontal floor witnesses inside the large hollow abutments.
        for x in [-1,1]:
            for z in [6,12,18]: box(label+' pier occupied floor',(x*(rx-9),y,z),(8,12,1.2),m['stone'])
    # Revision 2: perpendicular hollow vault gives the EAST/SIDE elevation its
    # own large opening, rather than two blank uprights and a box at the top.
    ts=[math.pi*i/72 for i in range(73)]
    inn=[(47*math.cos(t),2+40*math.sin(t)) for t in ts]
    inside=[(49*math.cos(t),2+42*math.sin(t)) for t in ts]
    outside=[(61*math.cos(t),2+52*math.sin(t)) for t in ts]
    out=[(63*math.cos(t),2+54*math.sin(t)) for t in ts]
    cross=[]
    cross.append(strip('TRANSVERSE inner load shell',inn,inside,-8,8,m['stone']))
    cross.append(strip('TRANSVERSE outer load shell',outside,out,-8,8,m['stone']))
    for y in [-7.8,7.8]:
        cross.append(strip('TRANSVERSE glazed occupied band',inside,outside,y-.18,y+.18,m['glass']))
        for j in range(0,73,6):
            a,b=inn[j],out[j]
            cross.append(beam('TRANSVERSE diaphragm',(a[0],y,a[1]),(b[0],y,b[1]),.35,m['dark']))
    root=bpy.data.objects.new('Transverse vault rotation',None); sc.collection.objects.link(root)
    for ob in cross: ob.parent=root
    root.rotation_euler.z=math.pi/2
    root.location.x=-30  # Keep the principal N-S civic axis visually open.
    # Upper bridge chambers join both arches. Deep occupied volume with two floors,
    # separated by a real central sky slot; no full thin slab over the forum.
    for x in [-22,22]:
        for z in [44,50]: box('Sky chamber floor',(x,0,z),(19,40,1.6),m['stone'])
        box('Sky chamber crown',(x,0,55),(19,40,3),m['stone'])
        for xx in [x-9.5,x+9.5]: box('Sky chamber glazed side',(xx,0,49.5),(.5,40,10),m['glass'])
        for yy in [-13,0,13]:
            beam('Sky chamber crossframe',(x-9,yy,44),(x+9,yy,55),.45,m['dark'])
    # Sweeping common deck: rising west/east landscape replaces isolated parcels.
    pts=[]
    for i in range(129):
        t=2*math.pi*i/128; pts.append((70*math.cos(t),49*math.sin(t),3+10*(math.sin(t)+1)))
    path_deck('Continuous elliptical public promenade',pts,8,2.2,m['stone'])
    for side in [-1,1]:
        rail=[(x+side*3.7*x/70,y+side*3.7*y/49,z+1.2) for x,y,z in pts]
        # Handrails are thin by function; primary architecture is volumetric.
        for i in range(len(rail)-1): beam('Promenade rail',rail[i],rail[i+1],.12,m['bronze'])
    for i in range(0,128,8):
        x,y,z=pts[i]; beam('Promenade ground support',(x,y,1),(x,y,z-2.2),.9,m['dark'])
    # Two broad radial pedestrian spines connect ground streets to elevated loop.
    for sign in [-1,1]:
        pts2=[(sign*(78-26*i/24),-70+40*i/24,1+6.1*i/24) for i in range(25)]
        path_deck('Street to common ramp',pts2,9,1.6,m['stone'])
    # Southern sunken-style forum bowl expressed as 9 concentric walkable terraces.
    for j in range(9):
        rad=12+j*2.4; z=.8+j*.65
        pp=[(rad*math.cos(t),-15+rad*.72*math.sin(t),z) for t in [math.pi+math.pi*i/64 for i in range(65)]]
        path_deck('Forum terrace '+str(j),pp,2.3,.65,m['terrace'])
    bpy.ops.mesh.primitive_cylinder_add(vertices=96,radius=12,depth=.7,location=(0,-15,.55)); bpy.context.object.name='Forum center'; bpy.context.object.data.materials.append(m['bronze'])
    # Two water/garden islands frame the public axis; paths remain visually open.
    for sign in [-1,1]:
        box('Reflecting pool',(sign*43,15,.55),(17,35,.25),m['water'])
        box('Planted island',(sign*43,44,1.1),(17,14,2.2),m['green'])
    # Human scale witnesses (1.75m) at paths, not structural decoration.
    for i,(x,y) in enumerate([(-8,-65),(8,-50),(0,10),(-38,-8),(38,8),(7,60),(-6,-12),(22,-60)]):
        beam('Scale person '+str(i),(x,y,1),(x,y,2.35),.24,m['dark'])
        bpy.ops.mesh.primitive_uv_sphere_add(segments=8,ring_count=4,radius=.23,location=(x,y,2.65)); bpy.context.object.data.materials.append(m['dark'])
    return sc

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--source',required=True); ap.add_argument('--out',required=True); ap.add_argument('--only',default='all'); args=ap.parse_args(sys.argv[sys.argv.index('--')+1:])
    out=Path(args.out).resolve(); out.mkdir(parents=True,exist_ok=True)
    data=json.loads(Path(args.source).read_text(encoding='utf-8',newline='\n'))
    m={n:mat(n,c,metal,rough) for n,c,metal,rough in [
        ('stone',(.74,.79,.78),.15,.38),('concrete',(.57,.62,.66),0,.7),('ground',(.075,.105,.13),0,.85),
        ('road',(.035,.048,.065),0,.8),('glass',(.075,.24,.29),.65,.23),('dark',(.035,.065,.08),.6,.4),
        ('bronze',(.66,.32,.10),.55,.38),('terrace',(.43,.49,.48),0,.6),('water',(.02,.23,.27),.6,.16),('green',(.16,.27,.21),0,.8),
        ('A',(.5,.62,.72),0,.6),('B',(.75,.65,.47),0,.6),('C',(.43,.58,.46),0,.6),('D',(.44,.60,.73),0,.6) ]}
    if args.only in ['all','baseline']:
        sc=baseline(data,m); d=out/'before_city'; d.mkdir(exist_ok=True); shots(sc,d,620,(0,0,22))
        # Same scale and lighting for culture district before/after comparison.
        district=bpy.data.scenes.new('A4_B_DISTRICT'); bpy.context.window.scene=district; configure(district)
        for ob in list(sc.objects):
            if ob.type=='MESH' and ob.name.startswith('B'):
                new=ob.copy(); new.data=ob.data.copy(); district.collection.objects.link(new); new.location.x-=90; new.location.y-=90
        box('District ground',(0,0,-2),(188,178,4),m['ground'])
        d=out/'before_district'; d.mkdir(exist_ok=True); shots(district,d,285,(0,0,24))
        bpy.ops.wm.save_as_mainfile(filepath=str(out/'a4_restored.blend'),compress=True)
    if args.only in ['all','proposal']:
        sc=proposal(m); d=out/'after'; d.mkdir(exist_ok=True); shots(sc,d,285,(0,0,24))
        bpy.context.window.scene=sc
        for screen in bpy.data.screens:
            for area in screen.areas:
                if area.type=='VIEW_3D':
                    area.spaces.active.region_3d.view_perspective='CAMERA'
                    area.spaces.active.overlay.show_overlays=False
                    area.spaces.active.shading.color_type='MATERIAL'
        bpy.ops.wm.save_as_mainfile(filepath=str(out/'a5_orbital_commons.blend'),compress=True)
        bpy.ops.object.select_all(action='DESELECT')
        for ob in sc.objects:
            if ob.type=='MESH': ob.select_set(True)
        bpy.ops.export_scene.gltf(filepath=str(out/'a5_orbital_commons.glb'),export_format='GLB',use_selection=True,use_active_scene=True)
        bpy.ops.wm.obj_export(filepath=str(out/'a5_orbital_commons.obj'),export_selected_objects=True)
        stats={'scene':sc.name,'mesh_objects':sum(ob.type=='MESH' for ob in sc.objects),'vertices':sum(len(ob.data.vertices) for ob in sc.objects if ob.type=='MESH'),'dimensions_units':[188,178,70],'max_elevation':66,'min_elevation':-4,'main_clear_span':96,'main_clear_height':49,'arch_radial_depth':[14,15],'arch_extrusion_depth':14,'sky_chamber_storeys':2,'public_loop_width':8,'public_loop_elevation_range':[3,23],'construction_status':'PROHIBITED','walkability':'NOT_TESTED','engineering':'NOT_VERIFIED'}
        (out/'model_facts.json').write_text(json.dumps(stats,indent=2)+'\n',encoding='utf-8',newline='\n')
    print('A5 ARTIFACTS COMPLETE',out)

if __name__=='__main__': main()
